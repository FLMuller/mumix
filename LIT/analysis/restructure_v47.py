"""restructure_v47.py  One-off, guarded: the page gets a new section 1 (literature summary) and 2 (theory), so the old sections move down by two.

    old 1-6  (the derivation)                -> 3-8      headings and the references to them in the text are renumbered
    old 7    (the data, generated)           -> 9        (build_data_sections.py writes it)
    old 8, 9 (tube model, 4-parameter model) -> removed; sections 10 (the fits tried) and 11 (the selected model) are written by build_fit_sections.py
    new 1, 2                                  written by build_intro_sections.py
The old page is kept as ../zprev/vortex-energy-balance_v46.html.  Running it again does nothing (it checks for the heading '3. One stretched vortex').
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(os.path.dirname(HERE), "vortex-energy-balance.html")


def shift_refs(text):
    """'section 4', 'sections 2 and 4', 'Section 6' ... : every number after 'section(s)' moves down by two (old 1-7 only)."""
    def one(m):
        head, nums = m.group(1), m.group(2)
        return head + re.sub(r"\d+", lambda n: str(int(n.group(0)) + 2) if 1 <= int(n.group(0)) <= 7 else n.group(0), nums)
    return re.sub(r"(\b[Ss]ections? )(\d+(?:(?: and |&ndash;|, )\d+)*)", one, text)


def main():
    t = open(PAGE, encoding="utf8").read()
    if "<h2>3. One stretched vortex</h2>" in t:
        print("already restructured")
        return
    a = t.index("<h2>1. One stretched vortex</h2>")
    d = t.index("<h2>7. The data: whole tubes and intense tubes</h2>")
    r = t.index("<h2>8. Tube model with Kolmogorov-scaled swirl")
    e = t.index("<h2>References</h2>")
    body = t[a:d]                                                     # old sections 1-6: hand-written
    body = shift_refs(body)
    for n in range(6, 0, -1):
        body = re.sub(r"<h2>%d\. " % n, "<h2>%d. " % (n + 2), body, count=1)
    data = t[d:r].replace("<h2>7. The data", "<h2>9. The data", 1)       # regenerated by build_data_sections.py
    new = ("<h2>10. The fits tried</h2>\n<p>@build_fit_sections@</p>\n<h2>11. The selected model</h2>\n<p>@build_fit_sections@</p>\n")
    t = t[:a] + body + data + new + t[e:]
    open(PAGE, "w", encoding="utf8", newline="\n").write(t)
    print("restructured")


if __name__ == "__main__":
    main()
